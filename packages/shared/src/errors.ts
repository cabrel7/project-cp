export function getErrorCode(code: string): ErrorCodeDef | undefined {
  if (!Object.hasOwn(ERROR_CODES, code)) return undefined
  return (ERROR_CODES as Record<string, ErrorCodeDef>)[code]
}

export function isRetryable(code: ErrorCode): boolean {
  return ERROR_CODES[code].isRetryable
}
