export interface ErrorCodeDef {
  readonly code: string
  readonly category: string
  readonly httpStatus: number
  readonly isRetryable: boolean
  readonly refundsCredits: boolean
}

function def(
  code: string,
  category: string,
  httpStatus: number,
  isRetryable = false,
  refundsCredits = false,
): ErrorCodeDef {
  return { code, category, httpStatus, isRetryable, refundsCredits }
}

